import { TestBed } from '@angular/core/testing';
import { provideRouter } from '@angular/router';
import { App } from './app';
import { routes } from './app.routes';

describe('App shell', () => {
  beforeEach(async () => {
    await TestBed.configureTestingModule({
      imports: [App],
      providers: [provideRouter(routes)],
    }).compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    expect(fixture.componentInstance).toBeTruthy();
  });

  it('exposes router-outlet for routed flow', () => {
    const fixture = TestBed.createComponent(App);
    fixture.detectChanges();
    expect((fixture.nativeElement as HTMLElement).querySelector('router-outlet')).toBeTruthy();
    expect(fixture.componentInstance.railIndexFromUrl('/learn/quiz')).toBe(5);
    expect(fixture.componentInstance.railIndexFromUrl('/welcome')).toBe(0);
    expect(fixture.componentInstance.railIndexFromUrl('/result')).toBe(6);
  });
});
